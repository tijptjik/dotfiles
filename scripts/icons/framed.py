#!/usr/bin/env python3
"""Record final frameless sign-off, then derive Rose Punk Framed offline.

Nothing is approved or generated by ordinary fullset/review builds. Run
`approve` only after the user signs off; `build` refuses absent or stale approval.
"""
import argparse
from functools import cache
import hashlib
import importlib.util
import json
import math
from pathlib import Path
import shutil
import tempfile
import xml.etree.ElementTree as ET
import zipfile

ROOT = Path(__file__).resolve().parents[2]
HERE = Path(__file__).resolve().parent
PRIMARY = ROOT / 'home/dot_local/share/icons/rose-punk/scalable/apps'
DEST = ROOT / 'home/dot_local/share/icons/rose-punk-framed'
APPROVAL = HERE / 'frameless-approved.json'
LAYOUT = HERE / 'framed-layout.json'
ASSETS = ROOT / '.local/icon-reviews/docs/assets/icon-framed'
SVG = 'http://www.w3.org/2000/svg'
ET.register_namespace('', SVG)
# Legacy/default transform, retained for callers without an explicit layout.
# Production builders use the reviewed per-icon layout registry.
TRANSFORM = 'translate(4.571429 3.571429) scale(0.857143)'
TILE = {'id': 'tile', 'x': '3', 'y': '2', 'width': '58', 'height': '58',
        'rx': '17', 'fill': '#26233a', 'stroke': '#555169',
        'stroke-opacity': '.45', 'stroke-width': '.65'}
INDEX = '''[Icon Theme]
Name=Rose Punk Framed
Comment=Secondary set derived from approved frameless Rose Punk originals
Directories=scalable/apps
Inherits=Neuwaita,Adwaita,hicolor

[scalable/apps]
Size=64
MinSize=16
MaxSize=512
Type=Scalable
Context=Applications
'''


def digest(data):
    return hashlib.sha256(data).hexdigest()


def transform(layout):
    if layout is None:
        return TRANSFORM
    scale, offset = layout['scale'], layout['offset']
    if not isinstance(offset, (list, tuple)) or len(offset) != 2:
        raise ValueError('Framed layout needs two offsets')
    numbers = [scale, *offset]
    if any(type(n) not in (int, float) or not math.isfinite(n) for n in numbers):
        raise ValueError('Framed layout needs a finite scale and two offsets')
    if not .35 <= scale <= 1.1 or any(abs(n) > 8 for n in offset):
        raise ValueError('Framed layout scale or offset is out of range')
    return f'translate({32 - 32 * scale + offset[0]:.6f} {31 - 32 * scale + offset[1]:.6f}) scale({scale:.6f})'


def load_layout(path=None, *, data=None, expected=None):
    policy = json.loads((LAYOUT if path is None else path).read_text()) if data is None else data
    if policy.get('schema') != 1 or not isinstance(policy.get('icons'), dict):
        raise ValueError('Invalid framed layout registry')
    entries = policy['icons']
    if expected is not None and set(entries) != set(expected):
        raise ValueError('Framed layout inventory mismatch: ' + ', '.join(sorted(set(entries) ^ set(expected))))
    for key, entry in entries.items():
        try:
            transform(entry)
            if len(entry['source_sha256']) != 64 or any(c not in '0123456789abcdef' for c in entry['source_sha256']):
                raise ValueError('Invalid source hash')
        except (KeyError, TypeError, ValueError) as error:
            raise ValueError(f'Invalid framed layout for {key}: {error}') from error
    return policy


def layout_source(source, key, policy):
    if key not in policy['icons']:
        raise ValueError(f'Missing framed layout: {key}')
    entry = policy['icons'][key]
    if digest(source) != entry['source_sha256']:
        raise ValueError(f'Framed layout source changed: {key}; review its optical sizing')
    return entry


@cache
def rasterizer():
    spec = importlib.util.spec_from_file_location('framed_rasterizer', HERE / 'frameless.py')
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module.render


def artwork_clearance(source, layout):
    """Measure the opaque contour against the tile's rounded rectangle."""
    from PIL import ImageChops, ImageFilter
    alpha = rasterizer()(source.decode(), 256).getchannel('A')
    mask = alpha.point(lambda a: 255 if a >= 16 else 0)
    edge = ImageChops.subtract(mask, mask.filter(ImageFilter.MinFilter(3)))
    scale, (dx, dy) = layout['scale'], layout['offset']
    distances = []
    for y in range(256):
        for x in range(256):
            if not edge.getpixel((x, y)):
                continue
            px = 32 + scale * ((x + .5) / 4 - 32) + dx
            py = 31 + scale * ((y + .5) / 4 - 32) + dy
            qx, qy = abs(px - 32) - 12, abs(py - 31) - 12
            distances.append(17 - math.hypot(max(qx, 0), max(qy, 0)) - min(max(qx, qy), 0))
    if not distances:
        raise ValueError('Empty framed artwork')
    return min(distances)


def check_fit(source, key, layout):
    margin = artwork_clearance(source, layout)
    if margin < 2:
        raise ValueError(f'Framed artwork crowds or extends outside tile: {key} ({margin:.2f} units)')
    return margin


def frame(source, layout=None):
    """Preserve all original nodes/paints beneath one outer sizing transform."""
    root = ET.fromstring(source)
    if root.get('viewBox') != '0 0 64 64':
        raise ValueError('Expected a 64 × 64 original')
    if any(n.get('id') == 'tile' for n in root.iter()):
        raise ValueError('Expected a frameless original, found a shared tile')
    group = ET.Element(f'{{{SVG}}}g', {'id': 'framed-artwork', 'transform': transform(layout)})
    for child in list(root):
        root.remove(child)
        group.append(child)
    root.append(ET.Element(f'{{{SVG}}}rect', TILE))
    root.append(group)
    return (ET.tostring(root, encoding='unicode') + '\n').encode()


def frame_theme(files, policy, aliases):
    """Aliases use their canonical icon's layout and exact source hash."""
    outputs = {}
    checked = set()
    for name, data in files.items():
        if name.startswith('scalable/apps/'):
            filename = Path(name).name
            key = aliases.get(filename, filename.removesuffix('.svg'))
            layout = layout_source(data, key, policy)
            if key not in checked:
                check_fit(data, key, layout)
                checked.add(key)
            data = frame(data, layout)
        outputs[name] = data
    return outputs


def check_layouts():
    import homepage
    from icon_data import gallery_catalog
    catalog = gallery_catalog(HERE)
    catalog.update(json.loads((HERE / 'command-icons.json').read_text()))
    services = json.loads((HERE / 'homepage.json').read_text())
    policy = load_layout(expected=set(catalog) | set(services))
    margins = {}
    for key in policy['icons']:
        folder = PRIMARY if key in catalog else homepage.DEST
        source = (folder / f'{key}.svg').read_bytes()
        margins[key] = check_fit(source, key, layout_source(source, key, policy))
    return margins


def inventory(primary, catalog):
    policy = load_layout()
    icons, aliases = {}, {}
    targets = {f'{key}.svg' for key in catalog}
    for key in sorted(catalog):
        source = (primary / f'{key}.svg').read_bytes()
        layout = layout_source(source, key, policy)
        check_fit(source, key, layout)
        frame(source, layout)
        icons[key] = digest(source)
    for path in sorted(primary.glob('symlink_*.svg')):
        target = path.read_text().strip()
        if target not in targets:
            raise ValueError(f'Alias {path.name} has no catalog original: {target}')
        aliases[path.name.removeprefix('symlink_')] = target
    return {'schema': 2, 'primary_theme': 'rose-punk',
            'icons': icons, 'aliases': aliases,
            'layout_sha256': digest(json.dumps(policy, sort_keys=True).encode()),
            'layouts': {key: policy['icons'][key] for key in icons}}


def require_approval(path, current):
    if not path.is_file():
        raise ValueError('Final frameless sign-off is pending. After approval, run framed.py approve.')
    if json.loads(path.read_text()) != current:
        raise ValueError('Frameless icons, aliases or framed layouts changed since sign-off; review and approve again.')


def build(primary, catalog, approval, dest, assets):
    current = inventory(primary, catalog)
    require_approval(approval, current)
    # Read every approved input and prepare every output before replacing anything.
    outputs = {}
    for key, expected in current['icons'].items():
        source = (primary / f'{key}.svg').read_bytes()
        if digest(source) != expected:
            raise ValueError(f'Original changed during build: {key}')
        outputs[key] = frame(source, current['layouts'][key])
    manifest = {'name': 'Rose Punk Framed', 'source_theme': current['primary_theme'],
                'approval_sha256': digest(approval.read_bytes()),
                'tile': TILE, 'layout_sha256': current['layout_sha256'],
                'layouts': current['layouts'],
                'icons': {key: {'frameless_sha256': current['icons'][key],
                                'framed_sha256': digest(value)}
                          for key, value in outputs.items()},
                'aliases': current['aliases']}
    dest.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix='.rose-punk-framed-', dir=dest.parent) as temporary:
        prepared = Path(temporary) / 'theme'
        apps = prepared / 'scalable/apps'
        apps.mkdir(parents=True)
        (prepared / 'index.theme').write_text(INDEX)
        for key, value in outputs.items():
            (apps / f'{key}.svg').write_bytes(value)
        for name, target in current['aliases'].items():
            (apps / f'symlink_{name}').write_text(target + '\n')
        assets.mkdir(parents=True, exist_ok=True)
        # The download uses ordinary SVG copies for aliases, so it is directly
        # installable without Chezmoi or platform-specific symlink extraction.
        with zipfile.ZipFile(assets / 'rose-punk-framed.zip', 'w', zipfile.ZIP_DEFLATED) as archive:
            files = {'index.theme': INDEX.encode()}
            files.update({f'scalable/apps/{key}.svg': value for key, value in outputs.items()})
            files.update({f'scalable/apps/{name}': outputs[Path(target).stem]
                          for name, target in current['aliases'].items()})
            for name, value in sorted(files.items()):
                info = zipfile.ZipInfo('rose-punk-framed/' + name, (2026, 1, 1, 0, 0, 0))
                info.compress_type = zipfile.ZIP_DEFLATED
                info.external_attr = 0o644 << 16
                archive.writestr(info, value)
        if dest.exists():
            shutil.rmtree(dest)
        prepared.rename(dest)
    (assets / 'manifest.json').write_text(json.dumps(manifest, indent=2) + '\n')
    return manifest


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('action', choices=('status', 'approve', 'build', 'check-layouts'), nargs='?', default='status')
    args = parser.parse_args()
    catalog = json.loads((HERE / 'catalog.json').read_text())
    catalog.update(json.loads((HERE / 'command-icons.json').read_text()))
    try:
        if args.action == 'check-layouts':
            margins = check_layouts()
            print(f'{len(margins)} framed layouts match source hashes; minimum tile clearance {min(margins.values()):.2f} units')
            return
        current = inventory(PRIMARY, catalog)
        if args.action == 'approve':
            APPROVAL.write_text(json.dumps(current, indent=2) + '\n')
            print(f'Recorded sign-off for {len(catalog)} frameless originals and their aliases')
        elif args.action == 'build':
            build(PRIMARY, catalog, APPROVAL, DEST, ASSETS)
            print(f'Built {len(catalog)} Rose Punk Framed icons, aliases, manifest and installable ZIP')
        else:
            require_approval(APPROVAL, current)
            print(f'{len(catalog)} frameless originals match final sign-off; framed build is ready')
    except (ValueError, FileNotFoundError) as error:
        parser.exit(1, str(error) + '\n')


if __name__ == '__main__':
    main()
